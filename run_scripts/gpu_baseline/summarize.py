"""Writes run_scripts/results/gpu_baseline/summary.md from benchmark_<host>.json (the output
of benchmark.py measure). Every number in the summary comes from that file.

Usage: python3 run_scripts/gpu_baseline/summarize.py --host <the GPU machine's hostname>
"""
import argparse
import json
from pathlib import Path

RESULTS = Path(__file__).resolve().parents[2] / "run_scripts" / "results" / "gpu_baseline"
CONFIGS = (("torch_fp32", "PyTorch FP32"), ("trt_fp32", "TensorRT FP32"), ("trt_int8", "TensorRT INT8"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", required=True, help="the hostname in benchmark_<host>.json")
    args = ap.parse_args()
    src = RESULTS / f"benchmark_{args.host}.json"
    d = json.loads(src.read_text())
    env, p, models = d["environment"], d["protocol"], d["models"]

    repeats = [r for cfgs in models.values() for c in cfgs.values() for r in c["repeats"]]
    valid = sum(r["valid"] for r in repeats)
    clocks = [c["summary"]["sm_clock_MHz_median"] for cfgs in models.values() for c in cfgs.values()]
    capped = sum(1 for r in repeats if r["monitor"]["clock_event_reasons"].get("sw_power_cap"))
    thermal = [sum(r["monitor"]["clock_event_reasons"].get(k, 0)
                   for k in ("sw_thermal_slowdown", "hw_thermal_slowdown")) for r in repeats]
    idle = [r["idle_W"] for r in repeats]
    samples = [r["monitor"]["samples"] for r in repeats]
    tmax = max(r["monitor"]["temperature_C"]["max"] for r in repeats)
    graphics = sorted({pid for r in repeats for pid in r["monitor"]["graphics_pids"]})

    lines = [
        f"# GPU baseline: {env['gpu']}, batch 1",
        "",
        f"Generated by `summarize.py` from `{src.name}` (measured {env['date']} on {env['host']}).",
        "",
        "## Latency (ms, median of the repeats' medians; p90 in parentheses)",
        "",
        "| Model | " + " | ".join(label for _, label in CONFIGS) + " |",
        "|---|" + "---|" * len(CONFIGS),
    ]
    for m, cfgs in models.items():
        cells = [f"{cfgs[c]['summary']['latency_ms_median']:.3f} ({cfgs[c]['summary']['latency_ms_p90']:.3f})"
                 for c, _ in CONFIGS]
        lines.append(f"| {m} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## Energy per inference (mJ, whole board; average power in W in parentheses)",
        "",
        "| Model | " + " | ".join(label for _, label in CONFIGS) + " |",
        "|---|" + "---|" * len(CONFIGS),
    ]
    for m, cfgs in models.items():
        cells = [f"{cfgs[c]['summary']['mJ_per_inference']:.1f} ({cfgs[c]['summary']['avg_power_W']:.0f})"
                 for c, _ in CONFIGS]
        lines.append(f"| {m} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## Method",
        "",
        "- **Workloads:** the float modules of `kernels/*.py`, the structure the compiler maps, batch 1: "
        "BERT encoder at 512 tokens; GPT-2 decoder stack and `ln_f`, one 1024-token causal pass (no "
        "embeddings or LM head); ViT encoder at 197 tokens; CNNs at 224 x 224. Random weights. "
        f"Kernels from {env['kernels_source']}.",
        "- **Configurations:** PyTorch eager FP32 (reference); TensorRT FP32; TensorRT INT8 (implicit "
        "quantization, FP32 fallback, 16 random calibration batches: sets the scales, not the speed, so "
        "these runs say nothing about INT8 accuracy). "
        f"TF32 off everywhere (`tf32: {env['tf32']}`), so FP32 is strict FP32.",
        f"- **Protocol, per configuration, {p['repeats']} repeats:** {p['idle_s']:.0f} s idle-power reading, "
        f"{p['warmup_s']:.0f} s warm-up, {p['latency_runs']} single inferences timed with CUDA events "
        f"(synchronized after each), then inferences back to back for {p['energy_s']:.0f} s. Energy per "
        "inference = NVML total-energy-counter delta over that loop / inferences: the whole board, "
        "static power included.",
        f"- **Validity:** a repeat counts only if no other compute process was on the GPU during it. "
        f"{valid} of {len(repeats)} repeats are valid. The desktop's graphics processes (pids "
        f"{', '.join(map(str, graphics))}) were present throughout and are not counted.",
        f"- **Clocks:** not locked (GPU Boost; power limit {env['power_limit_W']:.0f} W). Median SM clock "
        f"per configuration {min(clocks):.0f} to {max(clocks):.0f} MHz (maximum {env['max_sm_clock_MHz']} "
        f"MHz). The power cap was active in {capped} of {len(repeats)} repeats; thermal slowdown appeared "
        f"in {sum(1 for t in thermal if t)} repeats, at most {max(thermal)} of the {min(samples)} to "
        f"{max(samples)} samples per repeat (peak {tmax} C).",
        "- **Idle power** (`idle_W` in the JSON) is read right after the previous measurement, while our "
        f"process holds the GPU, so it is {min(idle):.0f} to {max(idle):.0f} W, above an unused card's. It "
        "only affects `dynamic_mJ_per_inference`; the energy above is the whole board.",
        f"- **Environment:** {env['gpu']}, driver {env['driver']}, torch {env['torch']} (CUDA "
        f"{env['torch_cuda']}), TensorRT {env['tensorrt']}, Python {env['python']}; process pinned to "
        f"CPUs {env['cpu_affinity'][0]}-{env['cpu_affinity'][-1]}.",
        "",
        "Reproduce: `run_scripts/gpu_baseline/run_all.sh` (see `benchmark.py` and `requirements.txt`).",
        "",
    ]
    (RESULTS / "summary.md").write_text("\n".join(lines))
    print(f"wrote {RESULTS / 'summary.md'}")


if __name__ == "__main__":
    main()
