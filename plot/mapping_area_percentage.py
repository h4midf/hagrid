"""Draw total area with mean component percentages in the caption.

python3 plot/mapping_area_percentage.py
python3 plot/mapping_area_percentage.py --extract  # refresh the area snapshot first
"""
import argparse
import math

import figure_data
from mapping_area_breakdown import DATA, OUT, CATEGORIES, extract
from mapping_latency import MODELS, LABELS, TARGETS, GROUP_STRIDE


def total_panel(target, title, data, ymin, ymax):
    rows = [(i * GROUP_STRIDE + j, row) for i, model in enumerate(MODELS)
            for j, row in enumerate(data[model])]
    ticks = ','.join(f'{x:g}' for x, _ in rows)
    caps = ','.join(f'{{$2^{{{int(math.log2(row["cap"]))}}}$}}' for _, row in rows)
    lines = [r'\begin{subfigure}[t]{0.325\textwidth}\centering\vspace{0pt}', r'\begin{tikzpicture}',
             r'\begin{axis}[width=1.10\linewidth,height=0.47\linewidth,',
             r'ybar,bar width=2.4pt,ymode=log,log basis y=10,',
             f'xmin=-0.7,xmax={(len(MODELS)-1)*GROUP_STRIDE+2.7:g},ymin={ymin:g},ymax={ymax:g},',
             (r'ylabel={Area (mm$^2$)},' if target == TARGETS[0][0] else '')
             + r'ylabel style={font=\tiny,at={(0.07,0.5)}},',
             r'tick label style={font=\tiny},x tick label style={rotate=60,anchor=north east},',
             r'ymajorgrids=true,major grid style={dotted,gray!45},axis x line*=bottom,',
             f'xtick={{{ticks}}},xticklabels={{{caps}}},]']
    coords = ' '.join(f'({x:g},{row["total_mm2"]:.9g})' for x, row in rows)
    lines.append(f'\\addplot+[fill=areaArray,draw=none] coordinates {{{coords}}};')
    for i, _ in enumerate(MODELS):
        if i:
            boundary = i * GROUP_STRIDE + (2 - GROUP_STRIDE) / 2
            lines.append(f'\\draw[dashed,gray!45] (axis cs:{boundary:g},{ymin:g}) -- (axis cs:{boundary:g},{ymax:g});')
        lines.append(f'\\coordinate (app{i}) at (axis cs:{i*GROUP_STRIDE+1:g},{ymin:g});')
    lines.append(r'\end{axis}')
    for i, label in enumerate(LABELS):
        lines.append(f'\\node[rotate=30,anchor=north,font=\\fontsize{{5}}{{5.5}}\\selectfont] at ([yshift=-2.3em]app{i}) {{{label}}};')
    lines += [r'\end{tikzpicture}', f'\\caption{{{title}}}\\label{{fig:mapping-area-percentage-{target}}}', r'\end{subfigure}']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--extract', action='store_true')
    if parser.parse_args().extract:
        extract()
    data = figure_data.read(DATA)['targets']
    totals = [row['total_mm2'] for models in data.values() for rows in models.values() for row in rows]
    ymin = 10 ** math.floor(math.log10(min(totals)))
    ymax = 10 ** math.ceil(math.log10(max(totals)*1.1))
    lines = ['% Generated by plot/mapping_area_percentage.py from plot/meta_data/mapping_area_breakdown.json.',
             r'\begin{figure*}[t]\centering\begingroup']
    lines += [f'\\definecolor{{{color}}}{{RGB}}{{{rgb}}}' for _, color, rgb in CATEGORIES]
    for i, (target, title) in enumerate(TARGETS):
        lines.append(total_panel(target, title, data[target], ymin, ymax))
        if i < len(TARGETS) - 1:
            lines.append(r'\hfill%')
    means = []
    for target, title in TARGETS:
        rows = [row for model in MODELS for row in data[target][model]]
        shares = [sum(row['groups_pct'][name] for row in rows) / len(rows)
                  for name, _, _ in CATEGORIES]
        means.append(title + ' (' + ', '.join(f'{value:.1f}' for value in shares) + r')\%')
    composition_text = ', '.join(means)
    lines += [r'\caption{Total area of greedy mappings at three array budgets per application on (a) 1F1C, (b) HFP, and (c) RSE, using a shared logarithmic scale. Budgets are labeled as powers of two. Mean area shares for arrays, interconnect/buffers, digital modules, and accelerator units, respectively, are '
              + composition_text + r'. These are arithmetic means across the eight applications and three budgets, with equal weight for each mapping. Arrays include local peripheral circuitry and RSE SRAM correction and dynamic-computation macros.}',
              r'\label{fig:mapping-area-percentage}', r'\endgroup\end{figure*}']
    path = OUT / 'mapping_area_percentage.tex'
    path.write_text('\n'.join(lines)+'\n')
    print(f'wrote {path}')


if __name__ == '__main__':
    main()
